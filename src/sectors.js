export function getSectorById(id) {
  const sec = SECTORS.find(s => s.id === Number(id)) || SECTORS[0];
  const lang = i18n.currentLocale || 'en';
  return {
    ...sec,
    name: lang === 'pt' ? sec.name_pt : sec.name_en,
    bossName: lang === 'pt' ? sec.bossName_pt : sec.bossName_en
  };
}
